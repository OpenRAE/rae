// Package contractgen generates Go transport bindings and the embedded corpus
// from the published contract authority. Generation never edits the authority.
package contractgen

import (
	"archive/zip"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"go/format"
	"io/fs"
	"maps"
	"path"
	"slices"
	"strconv"
	"strings"
	"unicode"
)

const rawType = "json.RawMessage"
const numberType = "json.Number"

const outputRoot = "implementations/go/internal/contract/"
const generatedHeader = "// Code generated by contractgen from contracts/schemas; DO NOT EDIT.\n\npackage binding\n\nimport \"encoding/json\"\n\n"

// Generate returns every generated file, keyed by its repository-relative path.
func Generate(source fs.FS) (map[string][]byte, error) {
	entries, inventoryErr := publications(source)
	if inventoryErr != nil {
		return nil, inventoryErr
	}
	if err := checkSpecification(source, entries); err != nil {
		return nil, err
	}
	output := map[string][]byte{}
	var registry strings.Builder
	registry.WriteString(generatedHeader)
	registry.WriteString("// Decode decodes schema-checked transport bytes. It grants no semantic authority.\nfunc Decode(id string, data []byte) (any, error) {\nswitch id {\n")
	for _, entry := range entries {
		formatted, rootName, err := generateBinding(source, entry)
		if err != nil {
			return nil, err
		}
		output[outputRoot+"binding/"+entry.ID+"_generated.go"] = formatted
		fmt.Fprintf(&registry, "case %q: var v %s; if err := json.Unmarshal(data, &v); err != nil { return nil, err }; return v, nil\n", entry.ID, rootName)
	}
	registry.WriteString("default: return nil, &json.UnsupportedValueError{Str: \"unknown contract\"}\n}\n}\n")
	formatted, err := format.Source([]byte(registry.String()))
	if err != nil {
		return nil, err
	}
	output[outputRoot+"binding/registry_generated.go"] = formatted
	archive, err := pack(source)
	if err != nil {
		return nil, err
	}
	const pieceSize = 131072
	for pos, n := 0, 0; pos < len(archive); pos, n = pos+pieceSize, n+1 {
		output[fmt.Sprintf("%scorpus/data/%04d", outputRoot, n)] = []byte(hex.EncodeToString(archive[pos:min(pos+pieceSize, len(archive))]) + "\n")
	}
	return output, nil
}

func generateBinding(source fs.FS, entry publication) ([]byte, string, error) {
	data, err := fs.ReadFile(source, entry.SchemaPath)
	if err != nil {
		return nil, "", err
	}
	var schema map[string]any
	if err = json.Unmarshal(data, &schema); err != nil {
		return nil, "", err
	}
	g := generator{root: schema, names: map[string]string{}, declarations: map[string]string{}, prefix: "d" + sum([]byte(entry.ID))[:10]}
	rootName := identifier(entry.ID)
	body, err := g.definition(schema, rootName)
	if err != nil {
		return nil, "", fmt.Errorf("generate %s: %w", entry.ID, err)
	}
	if body == rawType || body == numberType {
		body = "= " + body
	}
	g.declarations[rootName] = "// " + rootName + " is the transport representation of " + entry.ID + ".\ntype " + rootName + " " + body + "\n"
	var file strings.Builder
	file.WriteString(generatedHeader)
	for _, name := range slices.Sorted(maps.Keys(g.declarations)) {
		file.WriteString(g.declarations[name])
		file.WriteByte('\n')
	}
	// Keep the import in files whose schemas do not contain numbers or unions.
	file.WriteString("var _ json.RawMessage\n")
	formatted, err := format.Source([]byte(file.String()))
	if err != nil {
		return nil, "", fmt.Errorf("format %s: %w", entry.ID, err)
	}
	return formatted, rootName, nil
}

type publication struct {
	ID         string `json:"contract_id"`
	SchemaPath string `json:"schema_path"`
}

func publications(source fs.FS) ([]publication, error) {
	data, err := fs.ReadFile(source, "contracts/schema-publication-manifest.json")
	if err != nil {
		return nil, err
	}
	var manifest struct {
		Directory string `json:"entries_directory"`
	}
	if err = json.Unmarshal(data, &manifest); err != nil {
		return nil, err
	}
	if !strings.HasPrefix(manifest.Directory, "contracts/") || !fs.ValidPath(manifest.Directory) {
		return nil, errors.New("invalid publication directory")
	}
	files, err := fs.ReadDir(source, manifest.Directory)
	if err != nil {
		return nil, err
	}
	var entries []publication
	seen, schemas := map[string]bool{}, map[string]bool{}
	for _, file := range files {
		if file.IsDir() || path.Ext(file.Name()) != ".json" {
			continue
		}
		entry, readErr := readPublication(source, path.Join(manifest.Directory, file.Name()))
		if readErr != nil {
			return nil, readErr
		}
		if entry.ID == "" || seen[entry.ID] || schemas[entry.SchemaPath] {
			return nil, errors.New("invalid or duplicate publication")
		}
		seen[entry.ID], schemas[entry.SchemaPath] = true, true
		entries = append(entries, entry)
	}
	if len(entries) == 0 {
		return nil, errors.New("empty publication inventory")
	}
	return entries, checkPublishedSchemas(source, schemas)
}

func readPublication(source fs.FS, name string) (publication, error) {
	data, err := fs.ReadFile(source, name)
	if err != nil {
		return publication{}, err
	}
	var entry publication
	if err := json.Unmarshal(data, &entry); err != nil {
		return publication{}, err
	}
	if entry.ID != strings.TrimSuffix(path.Base(name), ".json") || !strings.HasPrefix(entry.SchemaPath, "contracts/schemas/") || !fs.ValidPath(entry.SchemaPath) {
		return publication{}, errors.New("invalid publication identity or path")
	}
	return entry, nil
}

func checkPublishedSchemas(source fs.FS, schemas map[string]bool) error {
	return fs.WalkDir(source, "contracts/schemas", func(name string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() && path.Ext(name) == ".json" && !schemas[name] {
			return errors.New("unpublished schema")
		}
		return nil
	})
}

func pack(source fs.FS) ([]byte, error) {
	var buffer bytes.Buffer
	writer := zip.NewWriter(&buffer)
	err := fs.WalkDir(source, "contracts", func(name string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			return nil
		}
		if d.Type()&fs.ModeSymlink != 0 {
			return errors.New("corpus symlink is forbidden")
		}
		data, err := fs.ReadFile(source, name)
		if err != nil {
			return err
		}
		file, err := writer.CreateHeader(&zip.FileHeader{Name: strings.TrimPrefix(name, "contracts/"), Method: zip.Deflate})
		if err != nil {
			return err
		}
		_, err = file.Write(data)
		return err
	})
	if err != nil {
		return nil, err
	}
	notice, err := fs.ReadFile(source, "THIRD_PARTY_NOTICES.md")
	if err != nil {
		return nil, err
	}
	file, err := writer.CreateHeader(&zip.FileHeader{Name: "provenance/THIRD_PARTY_NOTICES.md", Method: zip.Deflate})
	if err != nil {
		return nil, err
	}
	if _, err := file.Write(notice); err != nil {
		return nil, err
	}
	if err := writer.Close(); err != nil {
		return nil, err
	}
	return buffer.Bytes(), nil
}

// Check compares the complete generated output. Extra generated files fail too.
func Check(output fs.FS, want map[string][]byte) error {
	for name, data := range want {
		got, err := fs.ReadFile(output, name)
		if err != nil {
			return fmt.Errorf("missing generated file %s: %w", name, err)
		}
		if !bytes.Equal(got, data) {
			return fmt.Errorf("generated file differs: %s", name)
		}
	}
	return fs.WalkDir(output, strings.TrimSuffix(outputRoot, "/"), func(name string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			return nil
		}
		generated := strings.HasSuffix(name, "_generated.go") || strings.HasPrefix(name, outputRoot+"corpus/data/")
		if generated && want[name] == nil {
			return fmt.Errorf("extra generated file: %s", name)
		}
		return nil
	})
}

func sum(data []byte) string { digest := sha256.Sum256(data); return hex.EncodeToString(digest[:]) }

func identifier(s string) string {
	var out strings.Builder
	upper := true
	for _, r := range s {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			upper = true
			continue
		}
		if upper {
			r = unicode.ToUpper(r)
			upper = false
		}
		out.WriteRune(r)
	}
	result := out.String()
	if result == "" {
		return "Value"
	}
	if result[0] >= '0' && result[0] <= '9' {
		result = "N" + result
	}
	return result
}

type generator struct {
	root         map[string]any
	names        map[string]string
	declarations map[string]string
	prefix       string
}

func object(v any) map[string]any { m, _ := v.(map[string]any); return m }

func (g *generator) typ(node any) (string, error) {
	n := object(node)
	if n == nil {
		return rawType, nil
	}
	if ref, ok := n["$ref"].(string); ok {
		return g.reference(ref)
	}
	if n["anyOf"] != nil || n["oneOf"] != nil {
		return rawType, nil
	}
	if n["type"] == "object" && len(object(n["properties"])) > 0 {
		data, err := json.Marshal(n)
		if err != nil {
			return "", err
		}
		name := g.prefix + sum(data)[:12]
		if _, seen := g.declarations[name]; seen {
			return name, nil
		}
		g.declarations[name] = ""
		body, err := g.definition(n, name)
		if err != nil {
			return "", err
		}
		g.declarations[name] = "type " + name + " " + body + "\n"
		return name, nil
	}
	return g.definition(n, "")
}

func (g *generator) reference(ref string) (string, error) {
	if !strings.HasPrefix(ref, "#/$defs/") {
		return "", errors.New("unsupported non-definition reference")
	}
	if name, ok := g.names[ref]; ok {
		return name, nil
	}
	key := strings.ReplaceAll(strings.ReplaceAll(strings.TrimPrefix(ref, "#/$defs/"), "~1", "/"), "~0", "~")
	node, ok := object(g.root["$defs"])[key]
	if !ok {
		return "", errors.New("missing definition")
	}
	name := g.prefix + sum([]byte(ref))[:12]
	g.names[ref] = name
	body, err := g.typ(node)
	if err != nil {
		return "", err
	}
	// A reference alias to a struct retains a named transport definition.
	if body == rawType || body == numberType {
		g.names[ref] = body
		return body, nil
	}
	g.declarations[name] = "type " + name + " " + body + "\n"
	return name, nil
}

func (g *generator) definition(n map[string]any, _ string) (string, error) {
	if n["$ref"] != nil || n["anyOf"] != nil || n["oneOf"] != nil {
		return g.typ(n)
	}
	switch n["type"] {
	case "string":
		return "string", nil
	case "integer", "number":
		return numberType, nil
	case "boolean":
		return "bool", nil
	case "array":
		item, err := g.typ(n["items"])
		return "[]" + item, err
	case "object":
		properties := object(n["properties"])
		if len(properties) == 0 || n["additionalProperties"] != false {
			item, err := g.typ(n["additionalProperties"])
			return "map[string]" + item, err
		}
		var body strings.Builder
		body.WriteString("struct {\n")
		names := map[string]bool{}
		for _, key := range slices.Sorted(maps.Keys(properties)) {
			name := identifier(key)
			if names[name] {
				name += sum([]byte(key))[:8]
			}
			names[name] = true
			typ, err := g.typ(properties[key])
			if err != nil {
				return "", err
			}
			fmt.Fprintf(&body, "%s Field[%s] %s\n", name, typ, strconv.Quote("json:"+strconv.Quote(key+",omitzero")))
		}
		body.WriteString("}")
		return body.String(), nil
	default:
		return rawType, nil
	}
}
